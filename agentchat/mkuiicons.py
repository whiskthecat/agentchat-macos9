#!/usr/bin/env python3
"""Generate native Classic color icon families and monochrome fallbacks."""
from pathlib import Path
from PIL import Image
from icon_art import navigation_icon, ICON_PALETTE

HERE = Path(__file__).resolve().parent
PALETTE = ICON_PALETTE


def bits(image):
    return bytes(sum((image.getpixel((x + i, y)) != 0) << (7 - i) for i in range(8))
                 for y in range(image.height) for x in range(0, image.width, 8))


def indexed(image):
    cache = {}
    out = bytearray()
    for color in image.get_flattened_data():
        if color not in cache:
            cache[color] = min(range(len(PALETTE)), key=lambda i:
                               sum((color[c] - PALETTE[i][c]) ** 2 for c in range(3)))
        out.append(255 if cache[color] == 215 else cache[color])
    return bytes(out)


def resource(kind, resource_id, data):
    return f"data '{kind}' ({resource_id}, purgeable) {{\n" + '\n'.join(
        '    $"' + data[i:i + 16].hex().upper() + '"' for i in range(0, len(data), 16)) + '\n};\n'


def main():
    text = '/* Generated by mkuiicons.py; Classic Icon Manager color families. */\n'
    preview = Image.new('RGB', (480, 160), (221, 221, 221))
    for column, (resource_id, kind) in enumerate(((132, 'connect'), (133, 'new'), (134, 'settings'))):
        rgb, mask = navigation_icon(kind)
        art = rgb.convert('L').point(lambda value: 255 if value < 120 else 0)
        text += resource('ICON', resource_id, bits(art))
        text += resource('ICN#', resource_id, bits(art) + bits(mask))
        text += resource('icl8', resource_id, indexed(rgb))
        rgba = rgb.convert('RGBA')
        rgba.putalpha(mask)
        large = rgba.resize((160, 160), Image.Resampling.NEAREST)
        preview.paste(large, (160 * column, 0), large.getchannel('A'))
    (HERE / 'ui_icons.r').write_text(text)
    preview.save(HERE / 'navigation_preview.png')


if __name__ == '__main__':
    main()
